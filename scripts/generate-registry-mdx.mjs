#!/usr/bin/env node

/**
 * generate-registry-mdx.mjs
 *
 * Pipeline step 4: reads registry.json + per-item JSON files from public/registry/,
 * generates MDX documentation pages and meta.json navigation into content/registry/.
 *
 * Uses native Fumadocs components (Callout, Files, Cards, remarkNpm code blocks)
 * for rich, consistent docs pages.
 *
 * Preserves hand-authored MDX files (those without the .generated marker on line 1).
 */

import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const REGISTRY_JSON = join(ROOT, "registry.json");
const OUTPUT_DIR = join(ROOT, "content", "registry");

const GENERATED_MARKER =
  "{/* .generated - auto-generated by generate-registry-mdx.mjs, do not edit */}";
const GENERATED_MARKER_YAML =
  "# .generated - auto-generated by generate-registry-mdx.mjs";

const CATEGORY_ORDER = [
  "experiments",
  "components",
  "collected",
  "hooks",
  "mdx",
  "utilities",
];
const CATEGORY_TITLES = {
  experiments: "Experiments",
  components: "Components",
  collected: "Collected",
  hooks: "Hooks",
  mdx: "MDX",
  utilities: "Utilities",
};

const MAX_RELATED = 4;

function toJSArray(arr) {
  if (!arr?.length) {
    return "[]";
  }
  return JSON.stringify(arr);
}

function yamlQuote(str) {
  if (!str) {
    return '""';
  }
  if (
    str.includes(":") ||
    str.includes('"') ||
    str.includes("'") ||
    str.includes("#") ||
    str.includes("{") ||
    str.includes("}") ||
    str.includes("[") ||
    str.includes("]")
  ) {
    return `"${str.replace(/"/g, '\\"')}"`;
  }
  return str;
}

function shouldSkip(item) {
  if (item.type === "registry:style") {
    return true;
  }
  if (item.meta?.status === "wip") {
    return true;
  }
  if (item.name.endsWith(".story")) {
    return true;
  }
  return false;
}

async function isGeneratedFile(filepath) {
  try {
    const content = await readFile(filepath, "utf-8");
    return (
      content.startsWith(GENERATED_MARKER) ||
      content.includes(GENERATED_MARKER_YAML)
    );
  } catch {
    return false;
  }
}

async function cleanStaleGenerated() {
  if (!existsSync(OUTPUT_DIR)) {
    return;
  }

  for (const category of CATEGORY_ORDER) {
    const catDir = join(OUTPUT_DIR, category);
    if (!existsSync(catDir)) {
      continue;
    }

    let entries;
    try {
      entries = await readdir(catDir);
    } catch {
      continue;
    }

    for (const entry of entries) {
      if (!entry.endsWith(".mdx")) {
        continue;
      }
      const filepath = join(catDir, entry);
      if (await isGeneratedFile(filepath)) {
        await rm(filepath);
      }
    }
  }
}

/**
 * Find related items: same category + overlapping tags, capped at MAX_RELATED.
 */
function findRelated(item, allValidItems) {
  const tags = new Set(item.meta?.tags ?? []);
  if (tags.size === 0) {
    return [];
  }

  const scored = allValidItems
    .filter((other) => other.name !== item.name)
    .map((other) => {
      const otherTags = other.meta?.tags ?? [];
      const overlap = otherTags.filter((t) => tags.has(t)).length;
      const sameCategory = other.category === item.category ? 1 : 0;
      return { item: other, score: overlap * 2 + sameCategory };
    })
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, MAX_RELATED).map((s) => s.item);
}

/**
 * Build a Fumadocs <Files> tree from an item's file paths.
 */
function buildFilesTree(files) {
  if (!files?.length) {
    return "";
  }

  const tree = {};
  for (const f of files) {
    const parts = f.path.split("/");
    let node = tree;
    for (let i = 0; i < parts.length - 1; i++) {
      if (!node[parts[i]]) {
        node[parts[i]] = {};
      }
      node = node[parts[i]];
    }
    node[parts.at(-1)] = null;
  }

  function findComponentRoot(obj, path = []) {
    const keys = Object.keys(obj);
    if (keys.length === 1 && obj[keys[0]] !== null) {
      return findComponentRoot(obj[keys[0]], [...path, keys[0]]);
    }
    return { root: obj, path };
  }

  const { root, path: rootPath } = findComponentRoot(tree);
  const rootName = rootPath.join("/");

  function renderNode(obj, indent = 2) {
    const pad = " ".repeat(indent);
    const lines = [];
    const entries = Object.entries(obj).sort(([, a], [, b]) => {
      if (a === null && b !== null) {
        return 1;
      }
      if (a !== null && b === null) {
        return -1;
      }
      return 0;
    });
    for (const [name, children] of entries) {
      if (children === null) {
        lines.push(`${pad}<File name="${name}" />`);
      } else {
        lines.push(`${pad}<Folder name="${name}">`);
        lines.push(
          ...renderNode(children, indent + 2)
            .split("\n")
            .filter(Boolean)
        );
        lines.push(`${pad}</Folder>`);
      }
    }
    return lines.join("\n");
  }

  const inner = renderNode(root);
  return [
    "<Files>",
    `  <Folder name="${rootName}" defaultOpen>`,
    inner,
    "  </Folder>",
    "</Files>",
  ].join("\n");
}

/**
 * Build npm install block for dependencies (uses remarkNpm syntax).
 */
function buildNpmBlock(deps) {
  if (!deps?.length) {
    return "";
  }
  return ["```npm", `npm i ${deps.join(" ")}`, "```"].join("\n");
}

/**
 * Build a Usage code snippet showing import + basic render.
 */
function buildUsageSection(item) {
  const mainFile = item.files?.find(
    (f) =>
      f.path?.endsWith(".tsx") &&
      !f.path?.includes(".test.") &&
      !f.path?.includes(".story.")
  );
  if (!mainFile) {
    return "";
  }

  const filename = mainFile.name ?? mainFile.path?.split("/").pop() ?? "";
  const componentName = filename.replace(/\.(tsx|ts|jsx|js)$/, "");
  if (!componentName) {
    return "";
  }

  const targetDir = mainFile.target
    ? mainFile.target.replace(/\/[^/]+$/, "")
    : `components/${item.category}/${item.name}`;

  const lines = [
    "## Usage",
    "",
    "```tsx",
    `import { ${componentName} } from "@/${targetDir}/${componentName}";`,
    "",
    "export default function Example() {",
    `  return <${componentName} />;`,
    "}",
    "```",
  ];

  return lines.join("\n");
}

/**
 * Build Related section using Fumadocs Cards.
 */
function buildRelatedSection(related) {
  if (!related.length) {
    return "";
  }
  const cards = related
    .map(
      (r) =>
        `  <Card title="${r.title}" href="/registry/docs/${r.category}/${r.name}" />`
    )
    .join("\n");
  return ["## Related", "", "<Cards>", cards, "</Cards>"].join("\n");
}

function buildFrontmatter(title, description, lastModified) {
  const lines = [
    "---",
    GENERATED_MARKER_YAML,
    `title: ${yamlQuote(title)}`,
    `description: ${yamlQuote(description)}`,
  ];
  if (lastModified) {
    lines.push(`lastModified: ${yamlQuote(lastModified)}`);
  }
  lines.push("---");
  return lines;
}

function buildExperimentMdx(item, allValidItems) {
  const { name, title, description, type, category } = item;
  const deps = item.dependencies ?? [];
  const registryDeps = item.registryDependencies ?? [];
  const tags = item.meta?.tags ?? [];
  const tech = item.meta?.tech ?? [];
  const fileCount = item.files?.length ?? 0;
  const lastModified = item.meta?.created ?? null;
  const related = findRelated(item, allValidItems);

  const lines = [
    ...buildFrontmatter(title, description, lastModified),
    "",
    'import { ExperimentPreview } from "@/components/registry/ExperimentPreview";',
    'import { InstallCommand } from "@/components/registry/InstallCommand";',
    'import { RegistryMeta } from "@/components/registry/RegistryMeta";',
    'import { RegistrySourceCode } from "@/components/registry/RegistrySourceCode";',
    "",
    "<RegistryMeta",
    `  type="${type}"`,
    `  category="${category}"`,
    `  dependencies={${toJSArray(deps)}}`,
    `  registryDependencies={${toJSArray(registryDeps)}}`,
    `  tags={${toJSArray(tags)}}`,
    `  tech={${toJSArray(tech)}}`,
    `  fileCount={${fileCount}}`,
    "  verified={false}",
    "/>",
    "",
    "## Preview",
    "",
    `<ExperimentPreview slug="${name}" title="${title}" />`,
    "",
    "> [!TIP]",
    "> Open in full screen for the best experience.",
    "",
    "## Install",
    "",
    `<InstallCommand slug="${name}" />`,
    "",
  ];

  if (deps.length > 0) {
    lines.push("### Dependencies", "", buildNpmBlock(deps), "");
  }

  if (item.files?.length > 0) {
    lines.push("## File Structure", "", buildFilesTree(item.files), "");
  }

  lines.push("## Source", "", `<RegistrySourceCode slug="${name}" />`, "");

  const relatedSection = buildRelatedSection(related);
  if (relatedSection) {
    lines.push(relatedSection, "");
  }

  return lines.join("\n");
}

